export function getChartSampleManualData(chartType, subtype) {
  const t = String(chartType || '').trim().toLowerCase()
  const s = String(subtype || '').trim().toLowerCase()

  if (t === 'pie' && s.includes('nested')) {
    return {
      headers: ['项目', '内圈', '外圈'],
      rows: [
        ['A', '30', '50'],
        ['B', '20', '30'],
        ['C', '50', '20']
      ]
    }
  }
  if (t === 'pie') {
    return {
      headers: ['项目', '值'],
      rows: [
        ['A', '40'],
        ['B', '32'],
        ['C', '28']
      ]
    }
  }

  if (t === 'scatter' && s.includes('bubble')) {
    return {
      headers: ['X', 'Y', 'Z'],
      rows: [
        ['10', '20', '8'],
        ['15', '35', '12'],
        ['20', '10', '6'],
        ['30', '50', '15']
      ]
    }
  }
  if (t === 'scatter') {
    return {
      headers: ['X', 'Y'],
      rows: [
        ['10', '20'],
        ['15', '35'],
        ['20', '10'],
        ['30', '50']
      ]
    }
  }

  if (t === 'radar') {
    return {
      headers: ['维度', '指标1', '指标2'],
      rows: [
        ['速度', '80', '70'],
        ['力量', '60', '85'],
        ['技巧', '90', '65'],
        ['耐力', '70', '75'],
        ['智力', '85', '80']
      ]
    }
  }

  if (t === 'candlestick') {
    if (s.includes('volume')) {
      return {
        headers: ['日期', '开', '收', '低', '高', '成交量'],
        rows: [
          ['2024-01-01', '20', '26', '18', '28', '320'],
          ['2024-01-02', '26', '24', '22', '29', '280'],
          ['2024-01-03', '24', '30', '23', '31', '450'],
          ['2024-01-04', '30', '28', '27', '33', '390'],
          ['2024-01-05', '28', '35', '26', '36', '520']
        ]
      }
    }
    return {
      headers: ['日期', '开', '收', '低', '高'],
      rows: [
        ['2024-01-01', '20', '26', '18', '28'],
        ['2024-01-02', '26', '24', '22', '29'],
        ['2024-01-03', '24', '30', '23', '31'],
        ['2024-01-04', '30', '28', '27', '33'],
        ['2024-01-05', '28', '35', '26', '36']
      ]
    }
  }

  if (t === 'gauge') {
    return {
      headers: ['名称', '值'],
      rows: [['完成率', '50']]
    }
  }

  // 柱状图扩展类型
  if (t === 'bar') {
    if (s.includes('3d')) {
      return {
        headers: ['类别', '值'],
        rows: [
          ['A', '150'],
          ['B', '230'],
          ['C', '224'],
          ['D', '218'],
          ['E', '135'],
          ['F', '147'],
          ['G', '260']
        ]
      }
    }
    if (s.includes('gradient')) {
      return {
        headers: ['类别', '系列 1', '系列 2'],
        rows: [
          ['周一', '120', '200'],
          ['周二', '200', '320'],
          ['周三', '150', '250'],
          ['周四', '80', '160'],
          ['周五', '70', '110'],
          ['周六', '110', '130']
        ]
      }
    }
    if (s.includes('polar')) {
      return {
        headers: ['类别', '值'],
        rows: [
          ['A', '2.51'],
          ['B', '3.87'],
          ['C', '3.45'],
          ['D', '2.98'],
          ['E', '2.73'],
          ['F', '3.21']
        ]
      }
    }
  }

  // 折线图扩展类型
  if (t === 'line') {
    if (s.includes('dashed')) {
      return {
        headers: ['时间', '数据'],
        rows: [
          ['1 月', '220'],
          ['2 月', '182'],
          ['3 月', '191'],
          ['4 月', '234'],
          ['5 月', '290'],
          ['6 月', '330']
        ]
      }
    }
    if (s.includes('mark')) {
      return {
        headers: ['日期', '最高', '最低'],
        rows: [
          ['周一', '10', '2'],
          ['周二', '11', '3'],
          ['周三', '-1', '4'],
          ['周四', '16', '5'],
          ['周五', '17', '6'],
          ['周六', '18', '7'],
          ['周日', '19', '8']
        ]
      }
    }
    if (s.includes('radar')) {
      return {
        headers: ['维度', '预算', '开销'],
        rows: [
          ['销售', '5000', '4000'],
          ['管理', '14000', '10000'],
          ['信息技术', '10000', '9000'],
          ['客服', '5000', '5000'],
          ['研发', '19000', '15000'],
          ['市场', '9000', '7000']
        ]
      }
    }
  }

  // 饼图扩展类型
  if (t === 'pie') {
    if (s.includes('nightingale')) {
      return {
        headers: ['系列', '值'],
        rows: [
          ['A', '40'],
          ['B', '38'],
          ['C', '32'],
          ['D', '30'],
          ['E', '26']
        ]
      }
    }
    if (s.includes('label')) {
      return {
        headers: ['产品', '销量'],
        rows: [
          ['产品 A', '20%'],
          ['产品 B', '30%'],
          ['产品 C', '15%'],
          ['产品 D', '25%'],
          ['产品 E', '10%']
        ]
      }
    }
    if (s.includes('custom')) {
      return {
        headers: ['类别', '占比'],
        rows: [
          ['搜索引擎', '45%'],
          ['直接访问', '25%'],
          ['邮件营销', '15%'],
          ['联盟广告', '10%'],
          ['视频广告', '5%']
        ]
      }
    }
  }

  return {
    headers: ['类别', '系列1', '系列2'],
    rows: [
      ['一月', '120', '200'],
      ['二月', '150', '180'],
      ['三月', '90', '260'],
      ['四月', '170', '210']
    ]
  }
}
