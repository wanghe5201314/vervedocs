export function viewTranslate(translate: ViewTranslate | undefined, key: string, params?: Record<string, string | number>): string {
  const fallback = viewText[key] ?? key
  const result = translate?.(key, params)
  const text = !result || result === key ? fallback : result
  return text.replace(/\{(\w+)}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`))
}

// Translate template text nodes and display-only attributes, leaving form values intact.
const textKeys = new WeakMap<Text, string>()

export function translatePanel(root: HTMLElement, translate: ViewTranslate | undefined, prefix: string): void {
  const entries = Object.entries(viewText)
  const preferred = entries.filter(([key]) => key.startsWith(prefix) || key.startsWith('view.common.'))
  const byText = new Map([...entries, ...preferred].map(([key, value]) => [value, key]))
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  while (walker.nextNode()) {
    const node = walker.currentNode as Text
    const raw = node.textContent ?? ''
    const text = raw.trim()
    const key = textKeys.get(node) ?? byText.get(text)
    if (key) {
      textKeys.set(node, key)
      node.textContent = raw.replace(text, () => viewTranslate(translate, key))
    }
  }
  for (const el of [root, ...Array.from(root.querySelectorAll<HTMLElement>('*'))]) {
    const keyedText = el.dataset.i18nKey
    if (keyedText) el.textContent = viewTranslate(translate, keyedText)
    for (const attr of ['title', 'aria-label', 'placeholder']) {
      const marker = `i18n${attr === 'aria-label' ? 'AriaLabel' : attr[0].toUpperCase() + attr.slice(1)}`
      const raw = el.getAttribute(attr)
      const key = el.dataset[marker] ?? (raw && byText.get(raw))
      if (key) {
        el.dataset[marker] = key
        el.setAttribute(attr, viewTranslate(translate, key))
      }
    }
  }
}
