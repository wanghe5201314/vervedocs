export function resolveMaterialIcon(name: string): string | undefined {
  if (!name) return undefined
  let key = name.trim()
  if (key.startsWith('mdi ')) key = key.slice(4)
  if (key.startsWith('mdi-')) key = key.slice(4)
  return iconMap[key] || key.replace(/-/g, '_')
}

